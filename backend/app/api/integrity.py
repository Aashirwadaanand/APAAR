from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session
from typing import Optional, List
from datetime import datetime
import json

from backend.app.db.session import get_db
from backend.app.models.case import IntegrityCase
from backend.app.models.audit import AuditEvent
from backend.app.schemas.integrity import (
    IntegrityCaseResponse,
    CaseResolveRequest,
    IntegrityScanRequest,
    IntegrityScanResponse
)
from backend.app.services.integrity_engine import run_integrity_scan

router = APIRouter()

@router.get("/integrity/cases", response_model=List[IntegrityCaseResponse], tags=["Integrity Engine"])
def list_integrity_cases(
    status: Optional[str] = None,
    institution_id: Optional[str] = None,
    severity: Optional[str] = None,
    db: Session = Depends(get_db)
):
    """Retrieve integrity cases generated by the enrollment integrity engine."""
    query = db.query(IntegrityCase)

    if status:
        query = query.filter(IntegrityCase.status == status.upper())
    if institution_id:
        query = query.filter(IntegrityCase.institution_id == institution_id)
    if severity:
        query = query.filter(IntegrityCase.severity == severity.upper())

    return query.order_by(IntegrityCase.created_at.desc()).all()

@router.post("/integrity/scan", response_model=IntegrityScanResponse, tags=["Integrity Engine"])
def trigger_integrity_scan(payload: Optional[IntegrityScanRequest] = None, db: Session = Depends(get_db)):
    """
    Execute deterministic integrity scan across institutional records:
    - Missing required fields
    - Invalid APAAR syntax/checksum
    - Intra-institution duplicate APAAR IDs
    - Cross-institution duplicate APAAR IDs
    - Demographic conflicts
    - Intake capacity exceeded (with configurable policy)
    - Duplicate institutional student IDs
    """
    inst_id = payload.institution_id if payload else None
    policy = payload.intake_policy if payload else None

    result = run_integrity_scan(db, institution_id=inst_id, intake_policy=policy)

    return IntegrityScanResponse(
        scanned_students=result.scanned_students,
        scanned_institutions=result.scanned_institutions,
        findings_count=result.findings_count,
        new_cases_created=result.new_cases_created,
        existing_cases_updated=result.existing_cases_updated,
        message=f"Integrity scan finished. Identified {result.findings_count} findings ({result.new_cases_created} new cases created, {result.existing_cases_updated} updated)."
    )

@router.get("/integrity/cases/{case_id}", response_model=IntegrityCaseResponse, tags=["Integrity Engine"])
def get_case_by_id(case_id: int, db: Session = Depends(get_db)):
    """Retrieve details of a specific integrity case by ID."""
    case = db.query(IntegrityCase).filter(IntegrityCase.id == case_id).first()
    if not case:
        raise HTTPException(status_code=404, detail=f"Integrity case #{case_id} not found.")
    return case

@router.post("/integrity/cases/{case_id}/resolve", response_model=IntegrityCaseResponse, tags=["Integrity Engine"])
def resolve_integrity_case(
    case_id: int,
    payload: CaseResolveRequest,
    db: Session = Depends(get_db)
):
    """Resolve or dismiss an integrity case with an audited justification note."""
    case = db.query(IntegrityCase).filter(IntegrityCase.id == case_id).first()
    if not case:
        raise HTTPException(status_code=404, detail=f"Integrity case #{case_id} not found.")

    case.status = payload.status.upper()
    case.resolution_note = payload.resolution_note
    case.resolved_at = datetime.utcnow()
    case.updated_at = datetime.utcnow()

    db.commit()
    db.refresh(case)

    audit = AuditEvent(
        actor_label="Compliance Reviewer",
        action="INTEGRITY_CASE_RESOLVED",
        entity_type="IntegrityCase",
        entity_id=str(case.id),
        details_json=json.dumps({
            "case_id": case.id,
            "case_type": case.case_type,
            "status": case.status,
            "resolution_note": case.resolution_note
        })
    )
    db.add(audit)
    db.commit()

    return case
